def rio_segs():
    segs = []

    def rama(x, y, ang, L, w, g, gen):
        if gen > 11 or w < 0.6:
            return
        n = 14
        for k in range(n):
            ang += math.sin(k * 0.9 + gen) * 0.12 + rng.normal(0, 0.12)
            x2, y2 = x + L / n * math.cos(ang), y - L / n * math.sin(ang)
            segs.append((x, y, x2, y2, w, g + 0.08 * k / n))
            x, y = x2, y2
        g += 0.08
        for s in (-1, 1):
            if rng.random() < 0.95:
                rama(x, y, ang + s * rng.uniform(0.35, 0.8), L * rng.uniform(0.62, 0.8), w * 0.68, g, gen + 1)

    rama(W * 0.5, H + 20, math.pi / 2, 420, 22, 0, 0)
    return segs


def romanesco():
    """Spiral of spirals: cones placed by the golden angle, each cone a smaller spiral of buds, lit as spheres."""
    oro = math.pi * (3 - math.sqrt(5))
    w2, h2 = W * SS, H * SS
    img = Image.new("RGB", (w2, h2), (5, 4, 12))
    G = Image.new("L", (w2, h2), 0)
    d, dg = ImageDraw.Draw(img), ImageDraw.Draw(G)
    N = 760
    c0 = 24.5
    for i in range(N - 1, -1, -1):
        r = c0 * math.sqrt(i + 0.5)
        a = i * oro
        x, y = W / 2 + r * math.cos(a), H / 2 + r * math.sin(a)
        g = i / N
        rad = c0 * 0.46 * (1 + 0.0016 * r)
        cols = paleta(np.array([0.36 + 0.3 * g]))[0]
        for k, f in enumerate((1.0, 0.78, 0.55, 0.32, 0.14)):
            luz = 0.3 + 0.7 * k / 4
            col = tuple(int(255 * min(1, v * luz + 0.3 * (k == 4))) for v in cols)
            o = -rad * 0.28 * (1 - f)
            d.ellipse([(x + o - rad * f) * SS, (y + o - rad * f) * SS, (x + o + rad * f) * SS, (y + o + rad * f) * SS], fill=col)
        dg.ellipse([(x - rad - 2) * SS, (y - rad - 2) * SS, (x + rad + 2) * SS, (y + rad + 2) * SS], fill=int(1 + 254 * g))
    img = img.resize((W, H), Image.LANCZOS)
    glow = img.filter(ImageFilter.GaussianBlur(18))
    out = np.asarray(img, float) / 255 + np.asarray(glow, float) / 255 * 0.5
    Image.fromarray((np.clip(out / (1 + out * 0.2), 0, 1) * 255).astype(np.uint8)).save(OUT / "romanesco.jpg", quality=92)
    dilatar(G.resize((W, H), Image.NEAREST), 4).save(OUT / "romanesco-g.png")
    print("listo romanesco")


def costa():
    rng2 = np.random.default_rng(11)
    th = np.linspace(0, 2 * np.pi, 9000, endpoint=False)
    r = np.ones_like(th)
    for k in range(2, 1400):
        r += rng2.normal() * k ** -1.2 * 0.5 * np.cos(k * th + rng2.uniform(0, 2 * np.pi))
    xs = W / 2 + r * np.cos(th) * 820
    ys = H / 2 + r * np.sin(th) * 540
    segs = [(xs[i], ys[i], xs[(i + 1) % len(xs)], ys[(i + 1) % len(xs)], 2.4, i / len(xs)) for i in range(len(xs))]
    render("costa", segs, fase=0.62, rango=0.3)


