"""Computed images of the fractals of life for the pulse montage, each with a growth map so it can grow on screen.

Every structure is generated by a rule, never drawn by hand:
- relampago: stochastic leader that branches as it descends (growth = arrival time)
- venas: vessel tree whose radii split by Murray's law (r^3 = r1^3 + r2^3)
- neuronas: somas with tapering, branching dendrites and one axon
- pulmon: 3D bronchial tree, two daughters per branch rotated 90 degrees each generation, projected
- arbol: branching tree with noise
- rio: river network that branches upstream, width by order
- romanesco: spiral of spirals by the golden angle (phyllotaxis)
- costa: fractal island coast; cosmos: Zel'dovich cosmic web; mariposa: Hofstadter butterfly

Usage: PYTHONPATH=pylib python3 herramientas/planos.py [name ...]  ->  public/planos/<name>.jpg and <name>-g.png
"""
import math
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

RAIZ = Path(__file__).resolve().parent.parent
OUT = RAIZ / "public" / "planos"
OUT.mkdir(parents=True, exist_ok=True)
W, H = 2560, 1440
SS = 2

STOPS = np.array([[12, 8, 28], [70, 24, 92], [176, 64, 128], [238, 140, 120], [255, 244, 222], [150, 222, 226], [52, 110, 160]], float) / 255


def paleta(t):
    t = np.mod(t, 1.0) * (len(STOPS))
    i = np.floor(t).astype(int) % len(STOPS)
    f = t - np.floor(t)
    f = (f * f * (3 - 2 * f))[..., None]
    return STOPS[i] * (1 - f) + STOPS[(i + 1) % len(STOPS)] * f


def render(nombre, segs, fase=0.35, rango=0.55, fondo=(5, 4, 12), puntos=None):
    """segs: list of (x0, y0, x1, y1, width, growth 0..1). Coordinates in final pixels."""
    w2, h2 = W * SS, H * SS
    I = Image.new("L", (w2, h2), 0)
    G = Image.new("L", (w2, h2), 0)
    di, dg = ImageDraw.Draw(I), ImageDraw.Draw(G)
    # draw thick first so thin branches stay visible on top; growth uses the latest (thinner = later) value
    for x0, y0, x1, y1, w, g in sorted(segs, key=lambda s: -s[4]):
        ww = max(1, int(round(w * SS)))
        di.line([(x0 * SS, y0 * SS), (x1 * SS, y1 * SS)], fill=255, width=ww)
        dg.line([(x0 * SS, y0 * SS), (x1 * SS, y1 * SS)], fill=int(1 + 254 * min(1, max(0, g))), width=ww + 2)
        if ww > 3:
            r = ww / 2
            di.ellipse([x1 * SS - r, y1 * SS - r, x1 * SS + r, y1 * SS + r], fill=255)
    if puntos:
        for x, y, r, g, b in puntos:
            di.ellipse([(x - r) * SS, (y - r) * SS, (x + r) * SS, (y + r) * SS], fill=int(255 * b))
            dg.ellipse([(x - r - 1) * SS, (y - r - 1) * SS, (x + r + 1) * SS, (y + r + 1) * SS], fill=int(1 + 254 * g))
    I = I.resize((W, H), Image.LANCZOS)
    G = G.resize((W, H), Image.NEAREST)
    i = np.asarray(I, float) / 255
    g = np.asarray(G, float) / 255
    col = paleta(fase + g * rango) * i[..., None]
    col = np.maximum(col, np.asarray(Image.fromarray((np.clip(col, 0, 1) * 255).astype(np.uint8)), float) / 255)
    base = Image.fromarray((np.clip(col, 0, 1) * 255).astype(np.uint8))
    glow1 = np.asarray(base.filter(ImageFilter.GaussianBlur(6)), float) / 255
    glow2 = np.asarray(base.filter(ImageFilter.GaussianBlur(26)), float) / 255
    out = col + glow1 * 1.1 + glow2 * 0.9 + np.array(fondo) / 255
    out = out / (1 + out * 0.25)
    Image.fromarray((np.clip(out, 0, 1) * 255).astype(np.uint8)).save(OUT / f"{nombre}.jpg", quality=92)
    # growth map: spread to the glow so the halo appears with its branch
    dilatar(G).save(OUT / f"{nombre}-g.png")
    print("listo", nombre, len(segs), "segmentos")


def dilatar(G, pasos=18):
    """Spread each branch's growth time over its glow (about 80 px), keeping the earliest nearby value,
    so the halo appears with the first branch that reaches it and there is no visible edge."""
    a = np.asarray(G).copy()
    a[a == 0] = 255
    im = Image.fromarray(a)
    for _ in range(pasos):
        im = im.filter(ImageFilter.MinFilter(9))
    b = np.asarray(im).copy()
    b[b == 255] = 0
    return Image.fromarray(b)


rng = np.random.default_rng(7)


def relampago():
    segs = []
    pila = [(W * 0.52, -20.0, math.pi / 2, 1.0, 9.0, 0.0, 0)]
    while pila:
        x, y, ang, vida, ancho, g, prof = pila.pop()
        pasos = int(140 * vida)
        for k in range(pasos):
            ang += rng.normal(0, 0.38)
            ang = 0.75 * ang + 0.25 * (math.pi / 2)
            L = rng.uniform(7, 14)
            x2, y2 = x + L * math.cos(ang), y + L * math.sin(ang)
            g2 = g + 0.0062 + 0.002 * prof
            segs.append((x, y, x2, y2, ancho, g2))
            x, y, g = x2, y2, g2
            if y > H + 20:
                break
            if prof < 4 and rng.random() < 0.05 * (1.2 - prof * 0.2):
                pila.append((x, y, ang + rng.choice([-1, 1]) * rng.uniform(0.4, 1.0), vida * rng.uniform(0.25, 0.55), ancho * 0.45, g, prof + 1))
            ancho *= 0.998
    render("relampago", segs, fase=0.62, rango=0.18)


def venas():
    segs = []

    def rama(x, y, ang, r, g, gen):
        if r < 1.25 or gen > 11:
            return
        largo = r * rng.uniform(9, 16)
        n = 6
        for k in range(n):
            ang += rng.normal(0, 0.12)
            L = largo / n
            x2, y2 = x + L * math.cos(ang), y + L * math.sin(ang)
            segs.append((x, y, x2, y2, r * 2, g + 0.02 * k / n))
            x, y = x2, y2
        g += 0.02 + 0.02 * gen / 16
        a = rng.uniform(0.25, 0.75)
        r1 = r * a ** (1 / 3)  # Murray's law: r^3 = r1^3 + r2^3
        r2 = r * (1 - a) ** (1 / 3)
        # Murray's optimal angles: the thinner daughter turns more
        t1 = math.acos(np.clip((r ** 4 + r1 ** 4 - r2 ** 4) / (2 * r ** 2 * r1 ** 2), -1, 1))
        t2 = math.acos(np.clip((r ** 4 + r2 ** 4 - r1 ** 4) / (2 * r ** 2 * r2 ** 2), -1, 1))
        s = rng.choice([-1, 1])
        rama(x, y, ang + s * t1, r1, g, gen + 1)
        rama(x, y, ang - s * t2, r2, g, gen + 1)

    cx, cy = W * 0.5, H * 0.55
    for k, ang in enumerate(np.linspace(0, 2 * math.pi, 5, endpoint=False) + 0.3):
        rama(cx + 30 * math.cos(ang), cy + 30 * math.sin(ang), ang, 13.0, 0.0, 0)
    render("venas", segs, fase=0.24, rango=0.32)


def neuronas():
    segs = []
    puntos = []

    def dendrita(x, y, ang, r, g, gen, L0):
        if gen > 7 or r < 0.5:
            return
        n = 8
        largo = L0 * rng.uniform(0.7, 1.1)
        for k in range(n):
            ang += rng.normal(0, 0.18)
            L = largo / n
            x2, y2 = x + L * math.cos(ang), y + L * math.sin(ang)
            segs.append((x, y, x2, y2, r * 2, g + 0.05 * k / n))
            x, y = x2, y2
            r *= 0.97
        g += 0.05
        for s in (-1, 1):
            if rng.random() < 0.92:
                dendrita(x, y, ang + s * rng.uniform(0.3, 0.7), r * 0.78, g, gen + 1, L0 * 0.78)

    for k in range(6):
        sx, sy = rng.uniform(0.15, 0.85) * W, rng.uniform(0.2, 0.8) * H
        puntos.append((sx, sy, 16, 0.0, 1.0))
        g0 = rng.uniform(0, 0.15)
        for d in range(rng.integers(5, 8)):
            dendrita(sx, sy, rng.uniform(0, 2 * math.pi), 4.0, g0, 0, 120)
        # axon: long and wavy
        ang = rng.uniform(0, 2 * math.pi)
        x, y = sx, sy
        for i in range(160):
            ang += math.sin(i * 0.15) * 0.04 + rng.normal(0, 0.05)
            x2, y2 = x + 9 * math.cos(ang), y + 9 * math.sin(ang)
            segs.append((x, y, x2, y2, 2.2, g0 + i / 160 * 0.6))
            x, y = x2, y2
    render("neuronas", segs, fase=0.68, rango=0.22, puntos=puntos)


def rot(v, eje, a):
    eje = eje / np.linalg.norm(eje)
    return v * math.cos(a) + np.cross(eje, v) * math.sin(a) + eje * np.dot(eje, v) * (1 - math.cos(a))


