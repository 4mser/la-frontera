def pulmon_segs(gmax=13):
    segs3 = []

    def rama(p, d, plano, L, r, gen):
        if gen > gmax:
            return
        q = p + d * L
        segs3.append((p, q, r, gen / (gmax + 1)))
        n = np.cross(d, plano)
        for s in (-1, 1):
            ang = s * (0.5 + rng.normal(0, 0.06)) * (1.0 if s > 0 else 0.8)
            d2 = rot(d, plano, ang)
            plano2 = rot(plano, d2, math.pi / 2)  # each generation turns 90 degrees
            rama(q, d2, plano2, L * (0.8 + rng.normal(0, 0.04)), r * 0.79, gen + 1)

    rama(np.array([0.0, -1.0, 0.0]), np.array([0.0, 1.0, 0.0]), np.array([0.0, 0.0, 1.0]), 0.55, 0.06, 0)
    segs = []
    a = 0.5
    for p, q, r, g in segs3:
        def P(v):
            x = v[0] * math.cos(a) + v[2] * math.sin(a)
            z = -v[0] * math.sin(a) + v[2] * math.cos(a)
            f = 3.2 / (3.2 + z)
            return W / 2 + x * 520 * f, H * 0.12 + (v[1] + 1.0) * 520 * f
        x0, y0 = P(p); x1, y1 = P(q)
        segs.append((x0, y0, x1, y1, max(0.8, r * 520 * 0.5), g))
    return segs


def arbol():
    segs = []

    def rama(x, y, ang, L, w, g, gen):
        if gen > 13 or L < 3:
            return
        n = 4
        for k in range(n):
            a2 = ang + rng.normal(0, 0.06)
            x2, y2 = x + L / n * math.cos(a2), y - L / n * math.sin(a2)
            segs.append((x, y, x2, y2, w, g))
            x, y, ang = x2, y2, a2
        for s in (-1, 1):
            rama(x, y, ang + s * rng.uniform(0.25, 0.55), L * rng.uniform(0.7, 0.82), w * 0.7, g + 1 / 14, gen + 1)

    rama(W / 2, H + 10, math.pi / 2, 330, 26, 0, 0)
    render("arbol", segs, fase=0.18, rango=0.45)


